#!/usr/bin/env python3
"""Deterministic seed generator for Kahawa Guard.

    scripts/seedgen.py --members 300 --seed 42

Writes data/seed/{members,payments,dealer_register,products,buyers,contracts,
deliveries,advances,grading,sacco}.csv and plots.geojson. Re-runnable and
deterministic for a given --seed, so demos reproduce and diffs stay clean.

Everything is SYNTHETIC: fake names, reserved test phone ranges, a fake national
-ID prefix (99…), reserved .example domains. It has realistic SHAPE and
deliberate, bounded MESS (inactive members, stale phones, near-duplicate
registrations, held payments) so it reads like a real factory back office — but
it is not real people or companies.

The attack fixtures the scenes depend on are PINNED verbatim regardless of the
RNG (see FIXTURES below) and asserted at the end.
"""

from __future__ import annotations

import argparse
import csv
import json
import random
from datetime import date, timedelta
from pathlib import Path

SEED_DIR = Path(__file__).resolve().parent.parent / "data" / "seed"
BANNER = "# SYNTHETIC — generated by scripts/seedgen.py; not real people or companies."

FIRST = ["Wanjiku", "Kamau", "Njeri", "Mutahi", "Wairimu", "Kinuthia", "Nyokabi",
         "Githinji", "Mumbi", "Karanja", "Wambui", "Mwangi", "Nyawira", "Macharia",
         "Wangari", "Gitau", "Muthoni", "Ndungu", "Wanjiru", "Kariuki", "Njoki",
         "Maina", "Nduta", "Gichuru", "Waithera", "Kimani", "Wacera", "Mbugua"]
LAST = ["Mwangi", "Njoroge", "Kariuki", "Gichuru", "Ndung'u", "Maina", "Wambui",
        "Mbugua", "Kamau", "Macharia", "Kinyua", "Githenji", "Waweru", "Muriuki",
        "Karanja", "Njuguna", "Gatere", "Kibe", "Thuo", "Ngugi"]
SUBCOUNTIES = ["Mwea", "Gichugu", "Ndia", "Kirinyaga Central"]
VILLAGES = ["Kutus", "Kagio", "Kianyaga", "Kerugoya", "Sagana", "Baricho",
            "Difathas", "Kibingoti", "Kiamutugu", "Karumandi"]
FACTORIES = ["Kiamuthambi", "Kibingoti", "Thirikwa", "Karumandi", "Baricho"]
GRADES = ["AA", "AB", "PB", "C", "TT"]

# Members whose rows are PINNED (phones, names, and the attack properties).
# Names kept stable so the demo IDs match the member-site guide and prior runs.
PINNED_PHONE = {n: f"+2547{n:08d}" for n in range(1, 9)}   # KG-0001..0008
PINNED_NAME = {
    1: "Wanjiku Mwangi", 2: "Kamau Njoroge", 3: "Njeri Kariuki", 4: "Mutahi Gichuru",
    5: "Wairimu Ndung'u", 6: "Kinuthia Maina", 7: "Nyokabi Wambui", 8: "Githinji Mbugua",
}

# Plot polygons (rectangles) that the scenes assert on. (minx,miny,maxx,maxy)
FIXTURE_PLOTS = {
    "KG-0001": (37.050, -0.450, 37.055, -0.446, 6.0, False),   # overlaps KG-0004
    "KG-0002": (37.060, -0.452, 37.065, -0.448, 8.5, False),   # clean
    "KG-0003": (37.005, -0.395, 37.012, -0.390, 42.0, True),   # inside forest, mock
    "KG-0004": (37.053, -0.449, 37.058, -0.445, 11.0, False),  # overlaps KG-0001
    "KG-0005": (37.070, -0.460, 37.074, -0.457, 5.0, False),   # clean (Scene 4 contrast)
    "KG-0006": (37.076, -0.462, 37.080, -0.459, 7.5, False),
    "KG-0007": (37.082, -0.465, 37.086, -0.462, 9.0, False),
    "KG-0008": (37.088, -0.468, 37.092, -0.465, 6.5, False),
}

# Forest fixture bbox (data/seed/forest_2020_fixture.geojson) — generated plots
# must stay clear of it so only KG-0003 overlaps.
FOREST_BBOX = (37.0, -0.40, 37.02, -0.38)

DEALERS_FIXED = [
    ("DL-0042", "Kirinyaga Agrovet Ltd", "active", "2027-06-30"),
    ("DL-0043", "Mount Kenya Farm Inputs", "active", "2027-12-31"),
    ("DL-0044", "Thika Road Agro Supplies", "suspended", "2026-03-31"),
    ("DL-0045", "Highland Coffee Chemicals", "revoked", "2025-09-30"),   # the fake-circular dealer
    ("DL-0046", "Nyeri Cooperative Store", "active", "2028-01-31"),
]
PRODUCTS_FIXED = [
    ("Copper oxychloride 50WP", "true", "100", "Coffee berry disease; invented dosing for the demo"),
    ("Kahawa Guard Leaf Rust Mix", "true", "60", "Invented product"),
    ("Sulphur 80WG", "true", "80", "Invented product"),
    ("Rapid Grow Booster", "false", "", "Unregistered; the fake circular pushes this one"),
]


def rect(minx, miny, maxx, maxy):
    return [[[minx, miny], [maxx, miny], [maxx, maxy], [minx, maxy], [minx, miny]]]


def write_csv(name, header, rows):
    path = SEED_DIR / name
    with path.open("w", newline="") as f:
        f.write(BANNER + "\n")
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    return len(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--members", type=int, default=300)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--seasons", default="2025-main,2026-main")
    args = ap.parse_args()
    rng = random.Random(args.seed)
    seasons = args.seasons.split(",")

    members, plots = [], []
    deliveries, advances, grading, sacco, payments = [], [], [], [], []

    # grid for generated plots, well clear of the forest and of each other
    gx, gy, col = 37.10, -0.60, 0

    def gen_plot_rect():
        nonlocal gx, gy, col
        minx = gx + col * 0.006
        x = (minx, gy, minx + 0.003, gy + 0.003)
        col += 1
        if col >= 12:
            col = 0
            gy += 0.006
        return x

    seen_namevillage = {}
    dup_made = 0

    for i in range(1, args.members + 1):
        code = f"KG-{i:04d}"
        pinned = i in PINNED_PHONE
        phone = PINNED_PHONE.get(i, f"+2547{10_000_000 + i:08d}")

        first, last = rng.choice(FIRST), rng.choice(LAST)
        full_name = PINNED_NAME.get(i, f"{first} {last}")
        sub = rng.choice(SUBCOUNTIES)
        village = rng.choice(VILLAGES)

        status, phone_changed = "active", ""
        if not pinned:
            r = rng.random()
            if r < 0.05:
                status = "deceased"
            elif r < 0.08:
                status = "inactive"
            # ~5% stale/missing phone
            pr = rng.random()
            if pr < 0.03:
                phone = ""                         # missing number
            elif pr < 0.05:
                phone_changed = str(date(2026, 1, 1) - timedelta(days=rng.randint(30, 900)))
            # ~3% near-duplicate registration (same name+village, different code)
            key = (full_name.lower(), village.lower())
            if key in seen_namevillage and dup_made < max(1, args.members // 33) and rng.random() < 0.5:
                dup_made += 1
            else:
                seen_namevillage[key] = code
            # occasional casing mess
            if rng.random() < 0.06:
                village = village.upper()
            if rng.random() < 0.04:
                full_name = full_name.lower()

        dob = date(rng.randint(1958, 2003), rng.randint(1, 12), rng.randint(1, 28))
        joined = date(rng.randint(2010, 2025), rng.randint(1, 12), rng.randint(1, 28))
        nok = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        nok_phone = f"+2547{20_000_000 + i:08d}"
        national_id = f"99{rng.randint(100000, 999999)}"
        payout = f"MPESA-07{rng.randint(10, 99)}{rng.randint(100000, 999999)}"
        coop_id = rng.choice([1, 1, 2, 2, 3])

        members.append([code, phone, coop_id, payout, full_name, national_id,
                        dob.isoformat(), sub, village, nok, nok_phone,
                        joined.isoformat(), status, phone_changed])

        # --- plot ---
        has_plot = True
        if code in FIXTURE_PLOTS:
            minx, miny, maxx, maxy, acc, mock = FIXTURE_PLOTS[code]
            note = "inside forest_2020" if code == "KG-0003" else (
                "overlaps KG-0004" if code == "KG-0001" else
                "overlaps KG-0001" if code == "KG-0004" else "")
        else:
            # ~10% have no plot yet (newly joined); deceased never get one here
            if status == "deceased" or rng.random() < 0.10:
                has_plot = False
            else:
                minx, miny, maxx, maxy = gen_plot_rect()
                acc = round(rng.uniform(4.0, 15.0), 1)
                mock = rng.random() < 0.02         # a rare stray mock capture
                note = ""
        if has_plot:
            props = {"grower_code": code, "gps_accuracy_m": acc, "mock_location": mock}
            if note:
                props["note"] = note
            plots.append({"type": "Feature", "properties": props,
                          "geometry": {"type": "Polygon", "coordinates": rect(minx, miny, maxx, maxy)}})

        # --- deliveries + derived payment, per season ---
        if status == "deceased":
            member_seasons = []
        elif status == "inactive":
            member_seasons = seasons[:1]
        else:
            member_seasons = seasons
        for season in member_seasons:
            n_deliv = rng.randint(3, 12)
            total_kg = 0.0
            base_month = 10 if "main" in season else 5
            for _ in range(n_deliv):
                kg = round(rng.uniform(15, 120), 1)
                total_kg += kg
                d = date(int(season[:4]), base_month, rng.randint(1, 28))
                deliveries.append([code, season, d.isoformat(), kg, rng.choice(GRADES),
                                   rng.choice(FACTORIES)])
            rate = round(rng.uniform(55, 95), 2)
            amount = round(total_kg * rate, 2)
            pr = rng.random()
            pstatus = "paid" if pr < 0.78 else ("held" if pr < 0.90 else "pending")
            payments.append([code, season, round(total_kg, 1), amount, pstatus])
            # grading: one lot per season for ~60%
            if rng.random() < 0.6:
                grading.append([f"LOT-{i:04d}-{season[:4]}", code, season,
                                rng.choice(GRADES), round(rng.uniform(78, 88), 1),
                                round(rng.uniform(16, 20), 1),
                                date(int(season[:4]), base_month + 1, rng.randint(1, 28)).isoformat()])

        # --- advance (input credit) for ~35% ---
        if status != "deceased" and rng.random() < 0.35:
            kind = rng.choice(["cash", "fertiliser", "pesticide"])
            amt = round(rng.uniform(2000, 40000), 2)
            ast = rng.choices(["outstanding", "repaid", "written_off"], weights=[5, 4, 1])[0]
            dealer = rng.choice([d[0] for d in DEALERS_FIXED if d[2] == "active"])
            advances.append([code, kind, amt, date(2026, rng.randint(1, 9), rng.randint(1, 28)).isoformat(),
                             ast, dealer])

        # --- SACCO balances for active/inactive members ---
        if status != "deceased":
            savings = round(rng.uniform(500, 250000), 2)
            loan = round(rng.uniform(0, 180000), 2)
            lst = "none" if loan == 0 else rng.choice(["current", "current", "arrears"])
            sacco.append([code, savings, loan, lst,
                          date(2026, 9, rng.randint(1, 28)).isoformat()])

    # --- dealers: fixed five + generated ---
    dealers = list(DEALERS_FIXED)
    for j in range(47, 60):
        st = rng.choices(["active", "active", "active", "suspended"], weights=[6, 6, 6, 2])[0]
        yr = rng.randint(2026, 2029)
        dealers.append([f"DL-{j:04d}", f"{rng.choice(VILLAGES)} Agrodealers",
                        st, f"{yr}-{rng.randint(1,12):02d}-28"])

    # --- buyers + contracts (corporate layer; the leakable financials) ---
    buyer_names = ["Rift Valley Coffee Exporters Ltd", "Nordic Roasters A/S",
                   "Blue Mountain Trading GmbH", "Pacific Bean Co.",
                   "Highlands Specialty Coffee SA", "Kilele Export Partners",
                   "Aroma Global Importers", "Meridian Coffee Merchants"]
    countries = ["Kenya", "Denmark", "Germany", "USA", "Switzerland", "Kenya", "UAE", "UK"]
    buyers, contracts = [], []
    for k, (bn, cc) in enumerate(zip(buyer_names, countries), start=1):
        bcode = f"BUY-{k:04d}"
        slug = bn.split()[0].lower()
        buyers.append([bcode, bn, cc, f"{rng.choice(FIRST)} {rng.choice(LAST)}",
                       f"contact@{slug}.example", f"+44{rng.randint(2000000000, 2099999999)}",
                       f"{rng.choice(['Barclays','Equity','Stanbic','DNB','Commerzbank'])} Bank",
                       f"{rng.randint(10**9, 10**10 - 1)}",
                       f"{rng.choice(['BARC','EQBL','SBIC','DNBA','COBA'])}KENX",
                       f"A{rng.randint(100000000, 999999999)}X"])
        for season in seasons:
            contracts.append([f"CT-{k:04d}-{season[:4]}", bcode, season,
                              round(rng.uniform(20000, 120000), 0),
                              round(rng.uniform(4.5, 9.0), 2),
                              rng.choice(["FOB", "CIF"]),
                              date(int(season[:4]), rng.randint(1, 6), rng.randint(1, 28)).isoformat(),
                              rng.choice(["signed", "signed", "settled", "draft"])])

    # --- write everything ---
    counts = {}
    counts["members"] = write_csv("members.csv",
        ["grower_code", "phone", "coop_id", "payout_account_ref", "full_name",
         "national_id", "date_of_birth", "sub_county", "village", "next_of_kin",
         "next_of_kin_phone", "joined_on", "status", "phone_changed_on"], members)
    counts["payments"] = write_csv("payments.csv",
        ["grower_code", "season", "kilos", "amount_kes", "status"], payments)
    counts["dealers"] = write_csv("dealer_register.csv",
        ["licence_no", "name", "status", "valid_until"], dealers)
    counts["products"] = write_csv("products.csv",
        ["name", "registered", "max_dose_ml_per_20l", "notes"], PRODUCTS_FIXED)
    counts["buyers"] = write_csv("buyers.csv",
        ["buyer_code", "name", "country", "contact_name", "contact_email",
         "contact_phone", "bank_name", "bank_account", "settlement_swift", "kra_pin"], buyers)
    counts["contracts"] = write_csv("contracts.csv",
        ["contract_ref", "buyer_code", "season", "kilos", "price_per_kg_usd",
         "incoterm", "signed_at", "status"], contracts)
    counts["deliveries"] = write_csv("deliveries.csv",
        ["grower_code", "season", "delivered_on", "kilos", "grade", "factory"], deliveries)
    counts["advances"] = write_csv("advances.csv",
        ["grower_code", "kind", "amount_kes", "issued_on", "status", "dealer_licence"], advances)
    counts["grading"] = write_csv("grading.csv",
        ["lot_ref", "grower_code", "season", "grade", "cupping_score", "outturn_pct", "milled_on"], grading)
    counts["sacco"] = write_csv("sacco.csv",
        ["grower_code", "savings_kes", "loan_balance_kes", "loan_status", "last_statement"], sacco)

    (SEED_DIR / "plots.geojson").write_text(
        json.dumps({"type": "FeatureCollection", "features": plots}, indent=1) + "\n")
    counts["plots"] = len(plots)

    # --- fixture assertions (fail loudly if a scene would break) ---
    def bbox_overlap(a, b):
        return not (a[2] <= b[0] or b[2] <= a[0] or a[3] <= b[1] or b[3] <= a[1])

    pmap = {f["properties"]["grower_code"]: f["geometry"]["coordinates"][0] for f in plots}
    def bb(code):
        xs = [p[0] for p in pmap[code]]; ys = [p[1] for p in pmap[code]]
        return (min(xs), min(ys), max(xs), max(ys))

    assert bbox_overlap(bb("KG-0003"), FOREST_BBOX), "KG-0003 must overlap the forest"
    assert bbox_overlap(bb("KG-0001"), bb("KG-0004")), "KG-0001 must overlap KG-0004"
    assert not bbox_overlap(bb("KG-0005"), FOREST_BBOX), "KG-0005 must be clear of the forest"
    for c in ("KG-0005", "KG-0002"):
        for other, poly in pmap.items():
            if other == c:
                continue
            xs = [p[0] for p in poly]; ys = [p[1] for p in poly]
            assert not bbox_overlap(bb(c), (min(xs), min(ys), max(xs), max(ys))), \
                f"{c} must be a clean plot (overlaps {other})"
    assert any(d[0] == "DL-0045" and d[2] == "revoked" for d in dealers), "DL-0045 must be revoked"
    assert any(p[0] == "Rapid Grow Booster" and p[1] == "false" for p in PRODUCTS_FIXED), \
        "Rapid Grow Booster must be unregistered"

    print("seedgen OK:", ", ".join(f"{k}={v}" for k, v in counts.items()))


if __name__ == "__main__":
    main()
